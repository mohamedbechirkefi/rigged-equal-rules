"""Build research/paper/supplementary.md from committed result tables (generated once, reused).

Every table is read from results/EXP-NNN/tables/*.csv or results/exploratory/m4-confounders/*.csv;
nothing is typed by hand except the prose and the deviation list. Proportions are shown in pp
(x 100) with two decimals unless stated.

Usage: python3 scripts/build_supplementary.py
"""

from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research" / "paper" / "supplementary.md"


def rows(path: str) -> list[dict]:
    with (ROOT / path).open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def pp(v: str, d: int = 2) -> str:
    return f"{100 * float(v):.{d}f}"


def iv(r: dict, m: str, d: int = 2) -> str:
    return f"{pp(r[m + '_mean'], d)} [{pp(r[m + '_lo'], d)}, {pp(r[m + '_hi'], d)}]"


def table(headers: list[str], body: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(b) + " |" for b in body]
    return "\n".join(out)


def sha(path: str) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def main() -> int:
    s = ["<!-- SPDX-License-Identifier: LicenseRef-RIGGED-NC-Research-1.0 -->",
         "# Supplementary material",
         "",
         "Companion to `research/paper/manuscript.md` (M4, 2026-11-25). Independent research manuscript / preprint "
         "draft, not peer-reviewed. Tables are generated by `scripts/build_supplementary.py` from committed result "
         "files; gaps are group A minus group B in percentage points (pp) with 95% percentile bootstrap intervals "
         "over 20 seeds. Synthetic results are simulated.",
         "",
         "## S1. Complete experimental matrix",
         ""]
    body = []
    for e in ("EXP-001", "EXP-002", "EXP-003", "EXP-004"):
        cfg = json.loads((ROOT / f"research/experiments/{e}/config.json").read_text(encoding="utf-8"))
        cells = [c["cell"]["cell_id"] for c in cfg["cells"]]
        pols = sorted({p for c in cfg["cells"] for p in c["policies"]})
        body.append([e, str(len(cells)), ", ".join(pols), str(cfg["run_count"]), f"{cfg['seeds'][0]} to {cfg['seeds'][-1]}",
                     str(cfg["n"]), ", ".join(cells)])
    s += [table(["Experiment", "Cells", "Policies", "Runs", "Seeds", "n per population", "Cell IDs"], body), "",
          "All 1,780 runs completed with status ok; no metric was undefined (`results/EXP-NNN/results.json`). "
          "EXP-001's 240 P0 runs were also computed inside EXP-002 (DEC-020); the copies are identical apart from runtime.",
          "", "## S2. EXP-002, every cell and policy", "",
          "Source: `results/EXP-002/tables/summary.csv`.", ""]
    body = [[r["cell_id"], r["policy"], iv(r, "sr_gap"), iv(r, "eog"), iv(r, "ppv_gap"), iv(r, "fpr_gap")]
            for r in rows("results/EXP-002/tables/summary.csv")]
    s += [table(["Cell", "Policy", "SR gap", "EOG", "PPV gap", "FPR gap"], body), ""]
    s += ["## S3. Utility per capita relative to P0 (EXP-002)", "",
          "Paired over seeds; source `results/EXP-002/tables/policy_vs_p0.csv`; per capita, five decimals.", ""]
    body = [[r["cell_id"], r["policy"], f"{float(r['mean']):+.5f} [{float(r['boot_lo']):.5f}, {float(r['boot_hi']):.5f}]"]
            for r in rows("results/EXP-002/tables/policy_vs_p0.csv")]
    s += [table(["Cell", "Policy", "Difference from P0"], body), ""]
    s += ["## S4. P1 with the exact Gaussian posterior (EXPLORATORY, JRN-0015)", "",
          "Population values by numerical integration with the exact posterior in place of the 20-bin map, against "
          "the confirmatory binned P1 seed means. Exploratory: it changes no verdict. Source "
          "`results/exploratory/m4-confounders/p1_exact_posterior.csv`.", ""]
    body = []
    for r in rows("results/exploratory/m4-confounders/p1_exact_posterior.csv"):
        e, lo, hi = float(r["p1_exact_posterior_eog_pp"]), float(r["p1_binned_sim_eog_lo_pp"]), float(r["p1_binned_sim_eog_hi_pp"])
        body.append([r["cell_id"], f"{e:.2f}", f"{float(r['p1_binned_sim_eog_pp']):.2f} [{lo:.2f}, {hi:.2f}]",
                     "yes" if lo <= e <= hi else "no", f"{float(r['p1_exact_posterior_ppv_gap_pp']):.2f}",
                     f"{float(r['p1_binned_sim_ppv_gap_pp']):.2f}", f"{float(r['p0_population_eog_pp']):.2f}"])
    s += [table(["Cell", "P1 EOG, exact posterior", "P1 EOG, 20 bins (simulated)", "Exact inside interval",
                 "P1 PPV gap, exact", "P1 PPV gap, 20 bins", "P0 EOG, population"], body), ""]
    s += ["## S5. EXP-004, every cell and policy (real data)", "",
          "Source: `results/EXP-004/tables/summary.csv`, `policy_vs_p0.csv`, `base_rate_gap.csv`.", ""]
    body = [[r["cell_id"], r["policy"], iv(r, "sr_gap"), iv(r, "eog"), iv(r, "ppv_gap"), iv(r, "fpr_gap"), iv(r, "ece_gap")]
            for r in rows("results/EXP-004/tables/summary.csv")]
    s += [table(["Cell", "Policy", "SR gap", "EOG", "PPV gap", "FPR gap", "ECE gap"], body), ""]
    body = [[r["cell_id"], r["policy"], f"{float(r['mean']):+.4f} [{float(r['boot_lo']):.4f}, {float(r['boot_hi']):.4f}]"]
            for r in rows("results/EXP-004/tables/policy_vs_p0.csv")]
    s += [table(["Cell", "Policy", "Utility difference from P0"], body), ""]
    body = [[r["cell_id"], r["metric"], f"{pp(r['mean'])} [{pp(r['boot_lo'])}, {pp(r['boot_hi'])}]"]
            for r in rows("results/EXP-004/tables/base_rate_gap.csv")]
    s += [table(["Cell", "Quantity (evaluation halves, %)", "Mean [95% bootstrap]"], body), ""]
    s += ["## S6. Configurations and hashes", ""]
    body = []
    for e in ("EXP-001", "EXP-002", "EXP-003", "EXP-004"):
        prov = json.loads((ROOT / f"results/{e}/provenance.json").read_text(encoding="utf-8"))
        body.append([e, f"`{prov['experiment_protocol_sha256'][:16]}...`", f"`{prov['config_sha256'][:16]}...`",
                     f"`{sha(f'results/{e}/results.json')[:16]}...`", prov["git_revision"][:7]])
    s += [table(["Experiment", "Protocol SHA-256", "Config SHA-256", "results.json SHA-256", "Code revision"], body), "",
          "Full hashes: `results/EXP-NNN/provenance.json`, `research/freeze.json` and "
          "`research/publication/artifact_manifest.json`. Per-run configuration hashes are in each "
          "`research/experiments/EXP-NNN/config.json` (`run_config_hashes`).", ""]
    s += ["## S7. Robustness and exploratory results", "",
          "- EXP-002 tolerance sensitivity (protocol section 10): the H1 verdict is the same at 1, 2 and 5 pp (read from S2).",
          "- EXP-003 grids C and D: manuscript Table 4.",
          "- JRN-0014 (EXPLORATORY): EXP-003 rerun on seeds 1000 to 1019, analytic check 60 of 60 within 3 SE "
          "(`results/exploratory/exp-003-x/tables/analytic_check.csv`).",
          "- JRN-0015 (EXPLORATORY): S4.",
          "- JRN-0016 (EXPLORATORY): the EXP-004 score on the full test pool by the hours partition (no protected "
          "attribute used; no model fitted).", ""]
    g = rows("results/exploratory/m4-confounders/exp004_score_by_group.csv")
    body = [[r["group"], r["n"], r["positives"], pp(r["base_rate"]), pp(r["mean_logistic_probability"]),
             f"{float(r['calibration_in_the_large_pp']):+.2f}", pp(r["share_qualified_above_p70"]),
             pp(r["share_unqualified_above_p70"]), f"{float(r['score_q50_qualified']):.2f}",
             f"{float(r['score_q50_unqualified']):.2f}"] for r in g]
    s += [table(["Group", "n", "Qualified", "Base rate (%)", "Mean logistic probability (%)",
                 "Probability minus rate (pp)", "Qualified above pool p70 (%)", "Unqualified above pool p70 (%)",
                 "Median score, qualified", "Median score, unqualified"], body), ""]
    dec = rows("results/exploratory/m4-confounders/exp004_calibration_by_decile.csv")
    body = []
    for d in range(1, 11):
        a = next(r for r in dec if r["score_decile"] == str(d) and r["group"] == "A")
        b = next(r for r in dec if r["score_decile"] == str(d) and r["group"] == "B")
        body.append([str(d), a["n"], pp(a["observed_rate"]), b["n"], pp(b["observed_rate"]),
                     pp(a["mean_logistic_probability"])])
    s += ["Observed rate of Y = 1 by pool-wide score decile:", "",
          table(["Decile", "n (A)", "Observed rate A (%)", "n (B)", "Observed rate B (%)",
                 "Mean logistic probability A (%)"], body), ""]
    f = rows("results/exploratory/m4-confounders/exp004_features_by_label.csv")
    body = [[r["group"], r["label"], r["n"], f"{float(r['mean_age']):.2f}", f"{float(r['mean_education_num']):.2f}",
             pp(r["share_capital_gain_positive"]), pp(r["share_capital_loss_positive"])] for r in f]
    s += ["Score inputs by group and label (descriptive of this file only; no claim about people):", "",
          table(["Group", "Label", "n", "Mean age", "Mean education-num", "Capital gain > 0 (%)",
                 "Capital loss > 0 (%)"], body), ""]
    s += ["## S8. Experiment reports", "",
          "- EXP-001: `research/experiments/EXP-001/report.md`",
          "- EXP-002: `research/experiments/EXP-002/report.md`",
          "- EXP-003: `research/experiments/EXP-003/report.md`",
          "- EXP-004: `research/experiments/EXP-004/report.md`",
          "- Reproduction: `research/experiments/EXP-NNN/reproduction.md`",
          "- M4 interpretation, evidence audit and second review pass: `research/publication/interpretation.md`, "
          "`evidence_audit.md`, `review_pass_2.md`", ""]
    s += ["## S9. Deviations and owner decisions", "",
          table(["ID", "Date", "Scope", "What", "Decided by"], [
              ["A1 to A6 (DEC-012)", "2026-11-24", "All", "Pre-freeze amendments: H2 analytically determined, 20 seeds, budget, H1b non-directional, P3 tolerance 10, exploratory seeds 1000+", "Owner"],
              ["DEC-013, DEC-017", "2026-11-24", "EXP-004", "P3 capacity tolerance 30 (tied real score)", "Agent; ratified by the owner"],
              ["DEC-016", "2026-11-24", "EXP-004", "Round 3: sex as primary group (superseded, never run)", "Owner"],
              ["DEC-018", "2026-11-25", "EXP-004", "Option A: hours-per-week below 40 primary; sex removed from every analysis; JRN-0007 withdrawn", "Owner"],
              ["DEC-019, DEC-021", "2026-11-25", "EXP-003", "Implementation check 56 of 60; disclosed limitation on H4; no rerun", "Owner"],
              ["DEC-020", "2026-11-25", "EXP-001, EXP-002, EXP-004", "Shared P0 runs computed twice; base-rate table script written after the run; tolerance sensitivity read from intervals", "Agent"],
              ["DEC-022", "2026-11-25", "All", "M4 exploratory checks JRN-0015 and JRN-0016; one report number corrected (EXP-001 C4 value 6.31 to 6.30)", "Agent"],
              ["Report authorship", "2026-11-25", "All", "Experiment reports written from committed results only", "Owner"],
              ["C4 disclosure", "2026-11-24", "All", "Values of several cells seen exploratorily before the freeze", "Recorded in the freeze record"],
          ]), ""]
    OUT.write_text("\n".join(s) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
